// ─────────────────────────────────────────────────────────────────────────────
// b524 (2026-10-21) — the reads behind the Accounts home, and the postings.
//
// Every figure the Accounts page shows comes from here, so the page, the
// What-needs-me collector, the verifier and the forecast script cannot disagree
// about a number. The engines are elsewhere and stay pure:
//   src/lib/funding-expected.js   expected vs received arithmetic
//   src/lib/auto-allocate.js      the matching rules and the writes
//   src/lib/payroll-costs.js      the wage figure (b301 — never query
//                                 payroll_runs for one directly)
//   src/lib/allocation-period.js  which month a payment belongs to (b365)
//
// COUNTS AND TOTALS. Nothing here returns a child, family or staff name, or a
// line of bank text. The fee-run figures are aggregates over invoices; the
// payroll figures are run totals, and they are marked `is_pay` so a caller
// without canViewSalaries can strip them in one place.
// ─────────────────────────────────────────────────────────────────────────────

const FE = require('./funding-expected');

// ── Does this database have the b524 tables? ─────────────────────────────────
// It matters because things that load the HOST tree run against PROD: the 06:45
// What-needs-me cron is the one that caught b346 out
// (feedback_devonly_does_not_cover_cron). Until the b524 migration is applied on
// prod, every read here has to come back empty and say so — not throw
// `relation "funding_claim_receipts" does not exist` into a collector.
//
// Cached per process after the first look; a migration applied mid-process is
// not a case worth a round trip on every call.
const B524_TABLES = ['accounts_ledger_postings', 'payroll_file_imports',
  'payroll_run_import_mappings', 'bank_auto_matches', 'funding_claim_receipts',
  'card_settlements', 'bank_line_duplicate_reports', 'bank_line_duplicate_flags'];
let _ready = null;
async function ready(db) {
  if (_ready !== null) return _ready;
  const { rows } = await db.query(
    `SELECT table_name FROM information_schema.tables
      WHERE table_schema = 'ladn' AND table_name = ANY($1::text[])`, [B524_TABLES]);
  const have = new Set(rows.map(r => r.table_name));
  _ready = { ok: B524_TABLES.every(t => have.has(t)), present: [...have],
             missing: B524_TABLES.filter(t => !have.has(t)) };
  return _ready;
}
/** For tests, and for a process that applies the migration and carries on. */
function _resetReady() { _ready = null; }

const int = (v) => { const n = Number(v); return Number.isFinite(n) ? n : 0; };
const ymd = (v) => {
  if (!v) return null;
  if (typeof v === 'string') return v.slice(0, 10);
  const d = (v instanceof Date) ? v : new Date(v);
  if (isNaN(d)) return null;
  // Local getters. pg returns DATE as a LOCAL-midnight Date, so toISOString()
  // can roll the day back — the b298 note in src/lib/funding-periods.js.
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;
};

// ── Fee runs ─────────────────────────────────────────────────────────────────
// "When invoices for a month are generated, the run (count, total, funding
// deducted) appears in Accounts with no extra step."
//
// DERIVED, NOT RECORDED. There is deliberately no hook on POST /generate and no
// `fee_runs` table to keep in step with the invoices: the run IS the invoices for
// a service month, so it is a GROUP BY over them. That is what makes "with no
// extra step" true — a run generated by the monthly job, by /generate-itemised,
// by a regenerate or by hand all show up identically, and a deleted invoice
// leaves the figure correct rather than leaving a stale total behind. The dash
// died of being fed by hand; this does not repeat that.
//
// The month is the SERVICE month, from src/lib/allocation-period.js's order
// (service_from → the EyMan line → period_* → issued_on). b365 established that
// and PERIOD_SQL is its SQL form, so there is one definition, not two.
async function feeRuns(db, { limit = 24 } = {}) {
  const AP = require('./allocation-period');
  // allocation-period.js resolves the period of a PAYMENT via its invoice. For
  // the invoice itself the same ladder applies to the invoice row directly.
  const { rows } = await db.query(`
    WITH inv AS (
      SELECT i.id, i.status, i.amount_pence, i.gross_amount_pence,
             COALESCE(i.funding_reduction_pence, i.funding_deduction_pence, 0) AS funding_pence,
             COALESCE(i.discount_pence, 0) AS discount_pence,
             i.created_at, i.issued_on, i.sent_at, i.source, i.eylog_ref,
             COALESCE(
               date_trunc('month', i.service_from)::date,
               CASE WHEN i.period_year IS NOT NULL AND i.period_month IS NOT NULL
                    THEN make_date(i.period_year, i.period_month, 1) END,
               date_trunc('month', i.issued_on)::date,
               date_trunc('month', i.created_at)::date
             ) AS service_month
        FROM invoices i
       WHERE i.credit_note_for_id IS NULL
    )
    SELECT EXTRACT(YEAR  FROM service_month)::int AS period_year,
           EXTRACT(MONTH FROM service_month)::int AS period_month,
           COUNT(*)::int                            AS invoice_count,
           COUNT(*) FILTER (WHERE status = 'draft')::int  AS draft_count,
           COUNT(*) FILTER (WHERE status IN ('sent','overdue','partial','unpaid'))::int AS unpaid_count,
           COUNT(*) FILTER (WHERE status = 'paid')::int   AS paid_count,
           COALESCE(SUM(amount_pence),0)::bigint     AS total_pence,
           COALESCE(SUM(gross_amount_pence),0)::bigint AS gross_pence,
           COALESCE(SUM(funding_pence),0)::bigint    AS funding_deducted_pence,
           COALESCE(SUM(discount_pence),0)::bigint   AS discount_pence,
           COUNT(*) FILTER (WHERE eylog_ref IS NOT NULL
                              OR COALESCE(source ~* '^(eylog|eyman|import|migrat)', false))::int AS imported_count,
           MIN(COALESCE(issued_on, created_at::date))  AS first_issued,
           MAX(COALESCE(sent_at, created_at))          AS last_activity
      FROM inv
     WHERE service_month IS NOT NULL
     GROUP BY 1, 2
     ORDER BY 1 DESC, 2 DESC
     LIMIT $1`, [limit]);

  return rows.map(r => ({
    period_year: r.period_year, period_month: r.period_month,
    label: monthLabel(r.period_year, r.period_month),
    invoice_count: r.invoice_count,
    draft_count: r.draft_count, unpaid_count: r.unpaid_count, paid_count: r.paid_count,
    total_pence: int(r.total_pence),
    gross_pence: int(r.gross_pence),
    funding_deducted_pence: int(r.funding_deducted_pence),
    discount_pence: int(r.discount_pence),
    // A month whose invoices came out of EyLog is history, not a Wren fee run —
    // project_eylog_opening_balances_2026-10-06. Said, not hidden.
    imported_count: r.imported_count,
    is_imported_history: r.imported_count > 0 && r.imported_count === r.invoice_count,
    first_issued: ymd(r.first_issued),
    last_activity: r.last_activity,
    // b365: the only safe source for "what did this month really bill".
    period_rule: AP.PERIOD_SQL ? 'allocation-period.js service-month ladder' : 'service-month ladder',
  }));
}

const MONTHS = ['January', 'February', 'March', 'April', 'May', 'June',
                'July', 'August', 'September', 'October', 'November', 'December'];
const monthLabel = (y, m) => `${MONTHS[(int(m) || 1) - 1]} ${y}`;

// ── Payroll runs, and what they posted ───────────────────────────────────────
// `is_pay` on every money field. The caller strips them in ONE place
// (stripPay below) rather than each route remembering to.
async function payrollRuns(db, { limit = 24 } = {}) {
  const payrollCosts = require('./payroll-costs');
  const have = await ready(db);
  const { rows } = await db.query(`
    SELECT r.id, r.period_label, r.period_year, r.period_month, r.period_from, r.period_to,
           r.status, r.staff_count, r.warning_count, r.finalised_at,
           r.total_gross_pence, r.total_tax_pence, r.total_ni_pence, r.total_net_pence,
           r.total_pension_pence, r.total_employer_ni_pence,
           ${have.ok ? '(SELECT COUNT(*)::int FROM payroll_file_imports f WHERE f.run_id = r.id)' : '0'} AS file_count,
           ${have.ok ? '(SELECT MAX(created_at) FROM payroll_file_imports f WHERE f.run_id = r.id)' : 'NULL::timestamptz'} AS last_import_at
      FROM payroll_runs r
     ORDER BY r.period_from DESC
     LIMIT $1`, [limit]);

  return rows.map((r) => {
    // b301/b365: NEVER read total_employer_ni_pence as the answer on its own —
    // runs made before b301 store nothing there, and a direct query disagreed
    // with Finance → Intelligence by exactly the NI (June 2026 £33,173 vs
    // £34,080.50). payroll-costs.js employerCostPence() is the one place that
    // back-fills it, and `employer_ni_stored` says whether it had to.
    const cost = payrollCosts.employerCostPence(r);
    const employerNi = int(cost.employer_ni);
    const estimated = !cost.employer_ni_stored && employerNi > 0;
    return {
      id: r.id, label: r.period_label,
      period_year: r.period_year, period_month: r.period_month,
      period_from: ymd(r.period_from), period_to: ymd(r.period_to),
      status: r.status, staff_count: r.staff_count, warning_count: r.warning_count,
      finalised_at: r.finalised_at,
      file_count: r.file_count, last_import_at: r.last_import_at,
      is_pay: true,
      gross_pence: int(r.total_gross_pence),
      tax_pence: int(r.total_tax_pence),
      employee_ni_pence: int(r.total_ni_pence),
      employer_ni_pence: employerNi,
      employer_ni_estimated: estimated,
      pension_pence: int(r.total_pension_pence),
      net_pence: int(r.total_net_pence),
      // "Employer cost = gross + employer NI" (b301). Employee tax/NI/pension
      // come OUT of gross and are already inside it; employer PENSION is not
      // modelled by Wren at all, so this understates the true cost and says so.
      employer_cost_pence: int(cost.total),
      employer_cost_note: 'Gross plus employer NI. Employer pension contributions are not modelled by Wren, so the true cost is higher.',
    };
  });
}

/**
 * Strip every pay figure from a payload for a caller without canViewSalaries.
 *
 * OMITS the keys rather than zeroing them. b301: `pct(null, revenue)` returns 0,
 * and a wage bill shown as "0% of revenue" is worse than one that is absent.
 */
const PAY_KEYS = new Set(['gross_pence', 'tax_pence', 'employee_ni_pence', 'employer_ni_pence',
  'pension_pence', 'net_pence', 'employer_cost_pence', 'employer_ni_estimated']);
function stripPay(value) {
  if (Array.isArray(value)) return value.map(stripPay);
  if (value && typeof value === 'object') {
    const out = {};
    const isPayRow = value.is_pay === true;
    for (const [k, v] of Object.entries(value)) {
      if (isPayRow && PAY_KEYS.has(k)) continue;
      out[k] = stripPay(v);
    }
    if (isPayRow) out.pay_withheld = true;
    return out;
  }
  return value;
}

// ── The postings the ledger view reads ───────────────────────────────────────
/**
 * Post a payroll run's totals. Idempotent: re-posting the same run supersedes
 * its previous rows rather than adding a second set, so an edited and re-posted
 * run reads once and the old figures stay in the table with a `superseded_at`.
 */
async function postPayrollRun(db, runId, { actorId = null } = {}) {
  const have = await ready(db);
  if (!have.ok) return { error: 'b524_tables_missing', missing: have.missing };
  const { rows: [r] } = await db.query('SELECT * FROM payroll_runs WHERE id=$1', [runId]);
  if (!r) return { error: 'no_such_run' };
  const runs = await payrollRuns(db, { limit: 1000 });
  const mapped = runs.find(x => x.id === runId) || {};

  const postings = [
    ['gross',       int(mapped.gross_pence),       'Gross pay'],
    ['employer_ni', int(mapped.employer_ni_pence), 'Employer NI'],
    ['pension',     int(mapped.pension_pence),     'Pension contributions'],
    ['net',         int(mapped.net_pence),         'Net paid to staff'],
  ];

  let written = 0, superseded = 0;
  for (const [account, amount, label] of postings) {
    const sup = await db.query(`
      UPDATE accounts_ledger_postings SET superseded_at = now()
       WHERE source_kind='payroll' AND source_table='payroll_runs' AND source_id=$1
         AND account=$2 AND superseded_at IS NULL AND amount_pence <> $3`,
      [runId, account, amount]);
    superseded += sup.rowCount;
    const ins = await db.query(`
      INSERT INTO accounts_ledger_postings
        (source_kind, source_table, source_id, account, period_year, period_month,
         amount_pence, is_pay, label, evidence, posted_by)
      VALUES ('payroll','payroll_runs',$1,$2,$3,$4,$5,true,$6,$7,$8)
      ON CONFLICT (source_kind, source_table, source_id, account)
        WHERE superseded_at IS NULL AND source_id IS NOT NULL
      DO NOTHING
      RETURNING id`,
      [runId, account, r.period_year, r.period_month, amount, label,
       JSON.stringify({ run_label: r.period_label, status: r.status,
                        employer_ni_estimated: !!mapped.employer_ni_estimated }), actorId]);
    written += ins.rows.length;
  }
  return { run_id: runId, posted: written, superseded, accounts: postings.map(p => p[0]) };
}

/** The ledger view: postings by month, rolled up by account. */
async function ledger(db, { year = null, month = null, limit = 400 } = {}) {
  if (!(await ready(db)).ok) return [];
  const params = [];
  const where = ['superseded_at IS NULL'];
  if (year)  { params.push(year);  where.push(`period_year = $${params.length}`); }
  if (month) { params.push(month); where.push(`period_month = $${params.length}`); }
  params.push(limit);
  const { rows } = await db.query(`
    SELECT source_kind, account, period_year, period_month, is_pay,
           COUNT(*)::int AS n, SUM(amount_pence)::bigint AS pence,
           MAX(label) AS label, MAX(posted_at) AS last_posted_at
      FROM accounts_ledger_postings
     WHERE ${where.join(' AND ')}
     GROUP BY 1,2,3,4,5
     ORDER BY period_year DESC, period_month DESC, source_kind, account
     LIMIT $${params.length}`, params);
  return rows.map(r => ({
    source_kind: r.source_kind, account: r.account, label: r.label,
    period_year: r.period_year, period_month: r.period_month,
    period_label: monthLabel(r.period_year, r.period_month),
    is_pay: r.is_pay, postings: r.n, amount_pence: int(r.pence),
    last_posted_at: r.last_posted_at,
  }));
}

// ── Funding: expected vs received ────────────────────────────────────────────
/**
 * Cost every claim month and compare it with what arrived.
 *
 * One query for the children (all terms at once) rather than one per period, and
 * one for the receipts. Age is taken at each period's own claim_start inside
 * funding-expected.js, so the shared child list is correct for every month.
 */
async function fundingExpectedVsReceived(db, { year = null, month = null, today = new Date() } = {}) {
  const have = await ready(db);
  const [{ rows: periods }, { rows: rateRows }, { rows: receipts }, { rows: settings }] = await Promise.all([
    db.query(`
      SELECT p.*, t.name AS term_name, t.rate_under_2, t.rate_2yr_working_parents,
             t.rate_2yr_disadvantaged, t.rate_3yr_universal, t.rate_3yr_extended,
             t.eylog_term_id, t.source AS term_source
        FROM funding_claim_periods p JOIN funding_terms t ON t.id = p.term_id
       WHERE ($1::int IS NULL OR p.period_year = $1)
         AND ($2::int IS NULL OR p.period_month = $2)
       ORDER BY p.period_year DESC, p.period_month DESC, p.id`, [year, month]),
    db.query('SELECT age_band, funding_year, pence_per_hour FROM funding_rates'),
    // Receipts only exist where the b524 migration has been applied. On a database
    // without it the expected figures are still correct and received reads 0,
    // which is the honest answer rather than an exception.
    (await ready(db)).ok
      ? db.query(`
          SELECT r.claim_period_id, r.bank_line_id, r.amount_pence, r.received_on, r.is_adjustment
            FROM funding_claim_receipts r`)
      : Promise.resolve({ rows: [] }),
    db.query(`SELECT key, value FROM settings
               WHERE key IN ('accounts_funding_short_pct','accounts_funding_late_days')`),
  ]);
  if (!periods.length) return [];

  const sm = new Map(settings.map(r => [r.key, r.value]));
  const shortPct = Number(sm.get('accounts_funding_short_pct')) || 5;
  const lateDays = Number(sm.get('accounts_funding_late_days')) || 3;

  const termIds = [...new Set(periods.map(p => p.term_id))];
  const { rows: kids } = await db.query(`
    SELECT cf.term_id, cf.child_id, c.date_of_birth AS dob, cf.funding_type,
           cf.funded_hours_week, cf.total_hours_week, cf.stretched_funding,
           c.start_date, c.leave_date
      FROM child_funding cf JOIN children c ON c.id = cf.child_id
     WHERE cf.term_id = ANY($1::int[])`, [termIds]);
  // 2026-10-26: term dates, so a starter/leaver is claimed only for the term weeks they were here.
  const { rows: termRows } = await db.query(
    `SELECT start_date::text AS start, end_date::text AS end FROM school_terms`).catch(() => ({ rows: [] }));

  const byTerm = new Map();
  for (const k of kids) {
    if (!byTerm.has(k.term_id)) byTerm.set(k.term_id, []);
    byTerm.get(k.term_id).push(k);
  }
  const byPeriod = new Map();
  for (const r of receipts) {
    if (!byPeriod.has(r.claim_period_id)) byPeriod.set(r.claim_period_id, []);
    byPeriod.get(r.claim_period_id).push(r);
  }
  const rates = new Map(rateRows.map(r => [`${r.age_band}|${r.funding_year}`, r.pence_per_hour]));

  return periods.map((p) => {
    const period = Object.assign({}, p, { claim_start: ymd(p.claim_start), claim_end: ymd(p.claim_end),
      payment_expected: ymd(p.payment_expected), adj_payment_expected: ymd(p.adj_payment_expected) });
    const costed = FE.costPeriod(byTerm.get(p.term_id) || [], period, rates, p, termRows);
    return Object.assign(FE.compare(costed, byPeriod.get(p.id) || [], { shortPct, lateDays, today }),
      { term_name: p.term_name, receipts_tracked: have.ok });
  });
}

// ── The bank ─────────────────────────────────────────────────────────────────
async function bankSummary(db) {
  const { rows: [agg] } = await db.query(`
    SELECT COUNT(*)::int AS lines,
           COUNT(*) FILTER (WHERE excluded_reason IS NOT NULL)::int AS set_aside,
           COUNT(*) FILTER (WHERE excluded_reason IS NULL AND reconciled)::int AS reconciled,
           COUNT(*) FILTER (WHERE excluded_reason IS NULL AND NOT reconciled)::int AS open,
           COALESCE(SUM(amount_pence) FILTER (WHERE excluded_reason IS NULL AND NOT reconciled AND amount_pence > 0),0)::bigint AS open_credit_pence,
           COALESCE(SUM(-amount_pence) FILTER (WHERE excluded_reason IS NULL AND NOT reconciled AND amount_pence < 0),0)::bigint AS open_debit_pence,
           MAX(transaction_date) AS latest_line
      FROM bank_statement_lines`);
  const { rows: feeds } = await db.query(`
    SELECT s.source, COUNT(l.id)::int AS lines, MAX(s.last_synced_at) AS last_synced_at,
           MAX(l.transaction_date) AS latest_line
      FROM bank_statements s LEFT JOIN bank_statement_lines l ON l.statement_id = s.id
     GROUP BY 1 ORDER BY 1`);
  const have = await ready(db);
  const { rows: [q] } = have.ok ? await db.query(`
    SELECT COUNT(*) FILTER (WHERE status='queued')::int  AS queued,
           COUNT(*) FILTER (WHERE status='applied')::int AS applied,
           COUNT(*) FILTER (WHERE status='applied' AND auto)::int AS auto_applied,
           COUNT(*) FILTER (WHERE status='undone')::int  AS undone
      FROM bank_auto_matches`)
    : { rows: [{ queued: 0, applied: 0, auto_applied: 0, undone: 0 }] };
  return {
    lines: agg.lines, set_aside: agg.set_aside, reconciled: agg.reconciled, open: agg.open,
    open_credit_pence: int(agg.open_credit_pence), open_debit_pence: int(agg.open_debit_pence),
    latest_line: ymd(agg.latest_line),
    feeds: feeds.map(f => ({ source: f.source, lines: f.lines,
      last_synced_at: f.last_synced_at, latest_line: ymd(f.latest_line) })),
    // More than one feed on the same account is the duplicate cause
    // (src/lib/bank-duplicates.js). Surfaced on the page, not buried.
    feed_count: feeds.filter(f => f.lines > 0).length,
    allocations: q,
    allocations_tracked: have.ok,
  };
}

// ── The home page ────────────────────────────────────────────────────────────
/** Everything the Accounts landing page needs, in one round trip. */
async function home(db, { canViewSalaries = false, today = new Date() } = {}) {
  const have = await ready(db);
  const [fees, pay, funding, bank, led, dupes, imports] = await Promise.all([
    feeRuns(db, { limit: 13 }),
    payrollRuns(db, { limit: 13 }),
    fundingExpectedVsReceived(db, { today }),
    bankSummary(db),
    ledger(db, { limit: 60 }),
    have.ok ? db.query(`SELECT id, run_at, db_name, groups_found, lines_flagged, pence_flagged, applied_at
                FROM bank_line_duplicate_reports ORDER BY run_at DESC LIMIT 3`).then(r => r.rows) : [],
    have.ok ? db.query(`SELECT f.id, f.run_id, f.file_kind, f.filename, f.period_year, f.period_month,
                     f.rows_in_file, f.rows_matched, f.rows_unmatched, f.status, f.created_at
                FROM payroll_file_imports f ORDER BY f.created_at DESC LIMIT 8`).then(r => r.rows) : [],
  ]);

  // The funding months worth looking at first: short, then missing, then the
  // ones still awaiting a payment that is already due.
  const attention = funding.filter(f => f.is_short || f.is_missing);

  const payload = {
    as_at: ymd(today),
    fee_runs: fees,
    payroll_runs: pay,
    funding: funding.slice(0, 18),
    funding_attention: attention,
    bank,
    // The ledger needs its own filter, not stripPay.
    //
    // A posting row IS marked is_pay, but its money lives in `amount_pence`,
    // which is not in PAY_KEYS — it cannot be, because a FEE posting uses the
    // same column and that one is not pay. So stripPay left the whole payroll
    // posting, amount and all, in a deputy's payload: the key masking was right
    // and the wage bill still went out. Drop the rows instead, which is what
    // GET /accounts/ledger already does.
    ledger: canViewSalaries ? led : led.filter(p => !p.is_pay),
    ledger_pay_withheld: !canViewSalaries && led.some(p => p.is_pay),
    duplicate_reports: dupes,
    payroll_imports: imports,
    can_view_salaries: !!canViewSalaries,
    // Said out loud rather than rendered as zeroes: on a database without the
    // b524 migration the page shows the fee runs, the payroll runs and the
    // funding expectation, and nothing that needs the new tables.
    b524_ready: have.ok,
    b524_missing_tables: have.ok ? [] : have.missing,
  };
  return canViewSalaries ? payload : stripPay(payload);
}

